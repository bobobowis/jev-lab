export const HARNESS_ORDER: Harness[] = ["pi", "claude", "codex", "mcp"];

const full = (note?: string): Support => (note ? { status: "full", note } : { status: "full" });
const degraded = (note: string): Support => ({ status: "degraded", note });
const unavailable = (note: string): Support => ({ status: "unavailable", note });

