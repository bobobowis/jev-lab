/**
 * What each agent level and option can do in each harness. The lab serves it with every level and
 * the READMEs' table is generated from it, so the docs and the UI can't disagree.
 *   full: behaves as the level teaches it.
 *   degraded: runs, with the difference in the note.
 *   unavailable: the harness has no place for it; the lab won't start it.
 */
export type Harness = "pi" | "claude" | "codex" | "mcp";
export type Status = "full" | "degraded" | "unavailable";
export interface Support { status: Status; note?: string }
export type OptionKey = "A" | "B" | "C";

