/** One option's support in one harness; levels without hooks or tools (1 to 5) are full everywhere. */
export function capability(level: number, option: string, harness: Harness): Support {
  return CAPABILITIES[level]?.options[option as OptionKey]?.support[harness] ?? full();
}

/** Every option's support for a level, or null for a level that doesn't run in an agent. */
export function levelCapabilities(level: number): Record<OptionKey, Record<Harness, Support>> | null {
  const l = CAPABILITIES[level];
  if (!l) return null;
  return { A: l.options.A.support, B: l.options.B.support, C: l.options.C.support };
}

const cell = (s: Support) => (s.note ? `${s.status} (${s.note})` : s.status);

/** The matrix as a Markdown table, the one the READMEs carry between their jev:matrix markers. */
export function matrixMarkdown(): string {
  const rows = [
    `| Level | ${HARNESS_ORDER.map((h) => HARNESS_LABELS[h]).join(" | ")} |`,
    `|---|${HARNESS_ORDER.map(() => "---").join("|")}|`,
  ];
  for (const [level, l] of Object.entries(CAPABILITIES)) {
    for (const [key, o] of Object.entries(l.options)) {
      rows.push(`| ${level} ${key} ${o.name} | ${HARNESS_ORDER.map((h) => cell(o.support[h])).join(" | ")} |`);
    }
  }
  return rows.join("\n");
}

export const MATRIX_START = "<!-- jev:matrix (generated by `npm run docs` from packages/jev-kit/src/capabilities.ts) -->";
export const MATRIX_END = "<!-- /jev:matrix -->";

/** Replace the table between the markers, in the text's own line endings; unchanged without markers. */
export function withMatrix(text: string): string {
  const a = text.indexOf(MATRIX_START), b = text.indexOf(MATRIX_END);
  if (a < 0 || b < a) return text;
  const eol = text.includes("\r\n") ? "\r\n" : "\n";
  const table = matrixMarkdown().split("\n").join(eol);
  return `${text.slice(0, a + MATRIX_START.length)}${eol}${eol}${table}${eol}${eol}${text.slice(b)}`;
}
